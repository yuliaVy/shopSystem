    private void lstCategoriesValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstCategoriesValueChanged
        DefaultListModel productList = new DefaultListModel();
        //get a value selected
        String productCategorySelected = lstCategories.getSelectedValue().toString();
        //looping through a HashMap, entry type Map.Entry <Key, Value>
        //making HashMap iterable by .entrySet()
        for (Map.Entry<Integer, Product> productMapEntry : allProducts.entrySet())
        {
            //get actual product
            Product actualProduct = productMapEntry.getValue();
            //check if it equals to the selected clothes type
            if(actualProduct.getClass().getName().equals("pkg30499854_shop." + productCategorySelected))
            {
                productList.addElement(actualProduct);
            }
        }
        
        lstItems.setModel(productList);
// TODO add your handling code here:
    }//GEN-LAST:event_lstCategoriesValueChanged

