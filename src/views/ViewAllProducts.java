    private void btnAddToBasketActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToBasketActionPerformed
        //checks if anything is selected and throws error message if nothing is selected
        if (lstItems.getSelectedIndex()==-1)
        {
            lblConfirmation.setText("Error: Select Product to add first");
        }
        else
        {
            //converts selected value into product type
            Object selectedProductObj = lstItems.getSelectedValue();
            Product selectedProduct = (Product) selectedProductObj;
            
            //checking if the product is already in the basket
            if(currentOrder.isInBasket(selectedProduct.getProductId())== true)
            {
                lblConfirmation.setText("Selected Product is Already in the Basket");
            }
            else
            {
                //cheking and converting entered quantity to integer
            int quantity = 0;
            try {
                quantity = Integer.parseInt(txtQuantity.getText());
            } catch (NumberFormatException e) {
                lblConfirmation.setText("Please enter a valid quantity!");
            }
            //checks if quantity is valid and not higher than stock lvl
            if(selectedProduct.getStockLevel() >= quantity && !txtQuantity.getText().trim().isEmpty())
            {
                //creates new orderLine where passes Product and Quantity
                OrderLine ol = new OrderLine(selectedProduct, quantity);
                //adds orderLine into current Order
                currentOrder.addOrderLine(ol);
                //confirmation message
                lblConfirmation.setText("Product is added to basket");
            }
            else
            {
                lblConfirmation.setText("Product is not available or you've entered not valid quantity");
            }
            } 
        }
    }//GEN-LAST:event_btnAddToBasketActionPerformed

